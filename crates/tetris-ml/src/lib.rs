use candle_core::Device;

pub fn device() -> Device {
    if cfg!(feature = "candle-cuda") {
        Device::new_cuda(0).expect("CUDA device initialization must succeed in device")
    } else if cfg!(feature = "candle-metal") {
        Device::new_metal(0).expect("Metal device initialization must succeed in device")
    } else {
        Device::Cpu
    }
}
